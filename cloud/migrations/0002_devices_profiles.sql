-- ============================================================================
-- Synchrome — 0002: production schema for devices and profiles (account metadata)
-- ----------------------------------------------------------------------------
-- First production tables. Independent of the experimental e9_* objects.
--
--   public.devices   one row per Synchrome installation that signed in to the account
--   public.profiles  the account's Synchrome profiles ("Personal", "Trabajo", ...)
--
-- Ownership is `account_id = auth.uid()`; RLS is enabled AND forced so a user can only see
-- and change their own rows, whatever the client sends. The client authenticates with the
-- anon key + the user's JWT; the service role is never involved.
--
-- Properties: idempotent, explicit, reversible (0002_devices_profiles.rollback.sql),
--             guarded to run only on a Supabase database.
-- Apply (on the Synchrome server, by Codex): see cloud/migrations/README.md
-- ============================================================================

begin;

-- 0. Safety guard -------------------------------------------------------------
do $$
begin
  if to_regprocedure('auth.uid()') is null then
    raise exception
      'auth.uid() not found: this does not look like a Supabase database. Aborting 0002.';
  end if;
end $$;

-- 1. Shared trigger: keep updated_at fresh ------------------------------------
create or replace function public.synchrome_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

comment on function public.synchrome_set_updated_at() is
  'Synchrome: sets updated_at = now() on row update.';

-- 2. devices ------------------------------------------------------------------
-- device_id is generated by the client (UUID v4, stored in its app data dir) so an
-- installation can upsert itself idempotently without a round trip.
create table if not exists public.devices (
  device_id    uuid        primary key,
  account_id   uuid        not null default auth.uid(),
  name         text        not null,
  platform     text        not null,
  os_version   text,
  app_version  text        not null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  constraint devices_name_len        check (char_length(name) between 1 and 200),
  constraint devices_platform_len    check (char_length(platform) between 1 and 50),
  constraint devices_app_version_len check (char_length(app_version) between 1 and 50)
);

comment on table public.devices is
  'Synchrome installations that signed in to an account. Owner-scoped via RLS.';

create index if not exists devices_account_id_idx on public.devices (account_id);

drop trigger if exists devices_set_updated_at on public.devices;
create trigger devices_set_updated_at
  before update on public.devices
  for each row execute function public.synchrome_set_updated_at();

alter table public.devices enable row level security;
alter table public.devices force row level security;

drop policy if exists devices_select on public.devices;
create policy devices_select on public.devices
  for select to authenticated using (account_id = auth.uid());

drop policy if exists devices_insert on public.devices;
create policy devices_insert on public.devices
  for insert to authenticated with check (account_id = auth.uid());

drop policy if exists devices_update on public.devices;
create policy devices_update on public.devices
  for update to authenticated
  using (account_id = auth.uid()) with check (account_id = auth.uid());

drop policy if exists devices_delete on public.devices;
create policy devices_delete on public.devices
  for delete to authenticated using (account_id = auth.uid());

-- 3. profiles -----------------------------------------------------------------
create table if not exists public.profiles (
  id          uuid        primary key default gen_random_uuid(),
  account_id  uuid        not null default auth.uid(),
  name        text        not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint profiles_name_len check (char_length(name) between 1 and 200),
  constraint profiles_account_name_unique unique (account_id, name)
);

comment on table public.profiles is
  'Synchrome profiles (Personal, Work, ...) belonging to an account. Owner-scoped via RLS.';

create index if not exists profiles_account_id_idx on public.profiles (account_id);

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.synchrome_set_updated_at();

alter table public.profiles enable row level security;
alter table public.profiles force row level security;

drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
  for select to authenticated using (account_id = auth.uid());

drop policy if exists profiles_insert on public.profiles;
create policy profiles_insert on public.profiles
  for insert to authenticated with check (account_id = auth.uid());

drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles
  for update to authenticated
  using (account_id = auth.uid()) with check (account_id = auth.uid());

drop policy if exists profiles_delete on public.profiles;
create policy profiles_delete on public.profiles
  for delete to authenticated using (account_id = auth.uid());

-- 4. Privileges for the PostgREST role (RLS still applies on top) --------------
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.devices  to authenticated;
grant select, insert, update, delete on public.profiles to authenticated;
-- anon gets nothing on these tables.

commit;

-- End of 0002_devices_profiles.sql
